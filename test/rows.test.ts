import { describe, it, expect } from 'vitest';
import { buildSnapshot, projectLabel, stateIcon, rowsForHits, resolveTabSession, firstPrompts, labelMatchesTitle, tabMatches, trustedLearned, tabsToClose, candidateSessions, pinnedSessions, knownTitles } from '../src/core/rows.js';
import type { SessionHit } from '../src/core/query.js';
import type { SearchIndex, SessionMeta } from '../src/core/types.js';
import type { Liveness } from '../src/core/state.js';

const meta = (o: Partial<SessionMeta>): SessionMeta => ({
  sessionId: 'x', file: '/p/x.jsonl', extraFiles: [], projectDir: '-workspaces-aida', cwd: '/w', cwdExists: true,
  title: null, branches: [], prLinks: [], firstTs: 1, lastTs: 1, msgCount: 0, mtimeMs: 1, size: 1, ...o,
});
const live = (sessionId: string, state: Liveness['state'], lastWriteMs: number): [string, Liveness] =>
  [sessionId, { sessionId, verdict: 'awaiting-tool', state, lastWriteMs }];

const index: SearchIndex = {
  v: 1, builtAt: 0,
  sessions: [
    meta({ sessionId: 'a', title: 'Ledger GUI', branches: ['main', 'shobhit/ledger'], prLinks: [20231], lastTs: 900 }),
    meta({ sessionId: 'b', title: 'Deal forecast', lastTs: 800 }),
    meta({ sessionId: 'c', title: null, lastTs: 700, projectDir: '-workspaces-aida--claude-worktrees-figma' }),
    meta({ sessionId: 'd', title: 'Old one', lastTs: 100, cwdExists: false }),
  ],
  // prose is positional on sessions[]; c has a user prompt after an assistant line and a /clear echo (caveat + command), which must not title it
  prose: [{ s: 2, r: 'a', t: 1, x: 'hello' }, { s: 2, r: 'u', t: 1, x: '<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>' },
          { s: 2, r: 'u', t: 1, x: '<command-name>/clear</command-name>\n<command-message>clear</command-message>' }, { s: 2, r: 'u', t: 2, x: 'Match the Figma frame for the sequences dialog' }],
};

describe('projectLabel', () => {
  it('is the last -- segment of the sanitized dir name, as the Quick Pick has always shown', () => {
    expect(projectLabel('-workspaces-aida')).toBe('workspaces-aida');
    expect(projectLabel('-workspaces-aida--claude-worktrees-figma')).toBe('claude-worktrees-figma');
  });
});

describe('stateIcon', () => {
  it('maps each state to a codicon name', () => {
    expect(stateIcon({ state: 'running' })).toBe('loading~spin');
    expect(stateIcon({ state: 'attention', reason: 'tool-or-permission' })).toBe('bell-dot');
    expect(stateIcon({ state: 'attention', reason: 'your-turn' })).toBe('comment-discussion');
    expect(stateIcon({ state: 'attention', reason: 'stalled' })).toBe('warning');
    expect(stateIcon({ state: 'attention', reason: 'question' })).toBe('question');
    expect(stateIcon({ state: 'attention', reason: 'interrupted' })).toBe('circle-slash');
  });
});

describe('buildSnapshot', () => {
  it('orders ACTIVE by urgency then recency (spec §6)', () => {
    const liveness = new Map<string, Liveness>([
      live('a', { kind: 'running' }, 50),
      live('b', { kind: 'attention', reason: 'stalled' }, 99),
      live('c', { kind: 'attention', reason: 'your-turn' }, 10),
      live('d', { kind: 'attention', reason: 'tool-or-permission' }, 1),
      live('e', { kind: 'attention', reason: 'your-turn' }, 20),
    ]);
    const s = buildSnapshot(index, liveness);
    expect(s.active.map(r => r.sessionId)).toEqual(['d', 'e', 'c', 'a', 'b']);
  });

  it('joins index metadata onto live rows', () => {
    const s = buildSnapshot(index, new Map([live('a', { kind: 'running' }, 5)]));
    expect(s.active[0]).toMatchObject({
      sessionId: 'a', title: 'Ledger GUI', project: 'workspaces-aida', branch: 'shobhit/ledger', pr: 20231,
      cwdExists: true, state: 'running', lastWriteMs: 5,
    });
    expect(s.active[0]!.reason).toBeUndefined();
    const t = buildSnapshot(index, new Map([live('d', { kind: 'attention', reason: 'stalled' }, 5)]));
    expect(t.active[0]).toMatchObject({ reason: 'stalled', cwdExists: false });
  });

  it('falls back to the first user prompt, then to the id prefix, for a title', () => {
    const s = buildSnapshot(index, new Map([live('c', { kind: 'running' }, 5), live('zzzz-not-indexed-1234', { kind: 'running' }, 4)]));
    expect(s.active[0]!.title).toBe('Match the Figma frame for the sequences dialog');
    expect(s.active[1]!.title).toBe('zzzz-not');
    expect(s.active[1]!.project).toBe('');
  });

  it('HISTORY excludes ACTIVE ids, sorts by lastTs desc and caps at the limit', () => {
    const s = buildSnapshot(index, new Map([live('a', { kind: 'running' }, 5)]), { historyLimit: 2 });
    expect(s.history.map(r => r.sessionId)).toEqual(['b', 'c']);
    expect(s.history[0]).toMatchObject({ title: 'Deal forecast', lastTs: 800, msgCount: 0, cwdExists: true });
    expect(s.totalSessions).toBe(4);
  });

  it('works before the index exists and carries the indexing flag', () => {
    const s = buildSnapshot(null, new Map([live('a', { kind: 'running' }, 5)]), { indexing: true });
    expect(s.active[0]!.title).toBe('a');
    expect(s.history).toEqual([]);
    expect(s.totalSessions).toBe(0);
    expect(s.indexing).toBe(true);
  });
});

describe('scope', () => {
  it('drops indexed sessions the predicate rejects from ACTIVE, HISTORY and the total; keeps unindexed live ones', () => {
    const s = buildSnapshot(index, new Map([live('b', { kind: 'running' }, 5), live('new-not-indexed', { kind: 'running' }, 4)]),
                            { scope: 'workspace', inScope: m => m.sessionId !== 'b' && m.sessionId !== 'd' });
    expect(s.active.map(r => r.sessionId)).toEqual(['new-not-indexed']);
    expect(s.history.map(r => r.sessionId)).toEqual(['a', 'c']);
    expect(s.totalSessions).toBe(2);
    expect(s.scope).toBe('workspace');
  });
});

describe('rowsForHits / resolveTabSession', () => {
  it('turns search hits into rows with the shared title fallback, a snippet and live state', () => {
    const hits: SessionHit[] = [
      { session: index.sessions[0]!, score: 2, matchCount: 3, best: { text: 'we should paste the image here', role: 'u', index: 10 } },
      { session: index.sessions[2]!, score: 1, matchCount: 1, best: null },
    ];
    const rows = rowsForHits(hits, new Map([live('a', { kind: 'attention', reason: 'your-turn' }, 5)]), firstPrompts(index));
    expect(rows[0]).toMatchObject({ sessionId: 'a', title: 'Ledger GUI', matches: 3, pr: 20231, live: { state: 'attention', reason: 'your-turn', lastWriteMs: 5 } });
    expect(rows[0]!.snippet).toContain('paste the image');
    expect(rows[1]).toMatchObject({ sessionId: 'c', title: 'Match the Figma frame for the sequences dialog', snippet: null });
    expect(rows[1]).not.toHaveProperty('live');
  });
  it('resolves a Claude Code tab label to a row: exact title, ACTIVE first, prefix for a truncated label, else nothing', () => {
    const s = buildSnapshot(index, new Map([live('b', { kind: 'running' }, 5)]));
    expect(resolveTabSession('Deal forecast', s)).toBe('b');
    expect(resolveTabSession('Ledger GUI', s)).toBe('a');
    expect(resolveTabSession('Match the Figma frame', s)).toBe('c');
    expect(resolveTabSession('Something else entirely', s)).toBeUndefined();
    // two ACTIVE rows with one title: the most recently written wins, whatever the urgency order
    const dup = buildSnapshot({ ...index, sessions: [meta({ sessionId: 'x', title: 'Same' }), meta({ sessionId: 'y', title: 'Same' })], prose: [] },
                              new Map([live('x', { kind: 'attention', reason: 'your-turn' }, 9), live('y', { kind: 'running' }, 50)]));
    expect(dup.active.map(r => r.sessionId)).toEqual(['x', 'y']);
    expect(resolveTabSession('Same', dup)).toBe('y');
    expect(resolveTabSession('  ', s)).toBeUndefined();
  });
});

describe('tab labels (Claude Code cuts titles to 24 characters + "…")', () => {
  const known = [
    { sessionId: 'e', title: 'Email submission on calls page' },
    { sessionId: 'f', title: 'Email submission on call sheets' },     // same 24-character prefix as e
    { sessionId: 'g', title: 'Token usage optimization for the indexer' },
    { sessionId: 'h', title: 'Short title' },
  ];
  it('labelMatchesTitle: exact, or the label minus its ellipsis is a proper prefix of the title; never the reverse', () => {
    expect(labelMatchesTitle('Short title', 'Short title')).toBe(true);
    expect(labelMatchesTitle('Email submission on call…', 'Email submission on calls page')).toBe(true);
    expect(labelMatchesTitle('Email submission on call...', 'Email submission on calls page')).toBe(true);
    expect(labelMatchesTitle('Email submission on call…', 'Email submission on call')).toBe(false);   // nothing was cut off
    expect(labelMatchesTitle('Match the Figma frame', 'Match the Figma frame for the sequences dialog')).toBe(true);
    expect(labelMatchesTitle('Fix tests', 'Fix')).toBe(false);
    expect(labelMatchesTitle('  ', 'Fix')).toBe(false);
  });
  it('resolveTabSession understands the ellipsis', () => {
    const s = buildSnapshot({ ...index, sessions: [meta({ sessionId: 'e', title: 'Email submission on calls page' })], prose: [] },
                            new Map([live('e', { kind: 'attention', reason: 'your-turn' }, 5)]));
    expect(resolveTabSession('Email submission on call…', s)).toBe('e');
  });
  it('tabMatches lists every known session a label could be', () => {
    expect(tabMatches('Email submission on call…', known)).toEqual(['e', 'f']);
    expect(tabMatches('Token usage optimizatio…', known)).toEqual(['g']);
    expect(tabMatches('Claude Code', known)).toEqual([]);
  });
  it('trustedLearned drops a learned label that cannot be the session it names', () => {
    const learned = new Map([['Token usage optimizatio…', 'e'], ['Email submission on call…', 'e'], ['Claude Code', 'zz-unknown']]);
    expect(trustedLearned('Token usage optimizatio…', learned, known)).toBeUndefined();     // learned by accident: e is "Email…"
    expect(trustedLearned('Email submission on call…', learned, known)).toBe('e');
    expect(trustedLearned('Claude Code', learned, known)).toBe('zz-unknown');                 // no title to check against
    expect(trustedLearned('Nope', learned, known)).toBeUndefined();
  });
  describe('tabsToClose: only a tab that can be nobody else\'s', () => {
    const tab = (key: string, label: string) => ({ key, label });
    it('closes the tab a trusted learned label names, and nothing whose label points elsewhere', () => {
      const learned = new Map([['Email submission on call…', 'e']]);
      const tabs = [tab('1', 'Email submission on call…'), tab('2', 'Token usage optimizatio…')];
      expect(tabsToClose('e', tabs, learned, known)).toEqual({ close: [tabs[0]], ambiguous: [] });
      expect(tabsToClose('g', tabs, learned, known)).toEqual({ close: [tabs[1]], ambiguous: [] });
    });
    it('falls back to the title only when exactly one known session fits the label', () => {
      const tabs = [tab('1', 'Token usage optimizatio…'), tab('2', 'Email submission on call…')];
      expect(tabsToClose('g', tabs, new Map(), known).close).toEqual([tabs[0]]);
      // e and f share the label's 24 characters: leave it open and say so
      expect(tabsToClose('e', tabs, new Map(), known)).toEqual({ close: [], ambiguous: [tabs[1]] });
    });
    it('a label carried by two open tabs is ambiguous even when learned', () => {
      const learned = new Map([['Email submission on call…', 'e']]);
      const tabs = [tab('1', 'Email submission on call…'), tab('2', 'Email submission on call…')];
      expect(tabsToClose('e', tabs, learned, known)).toEqual({ close: [], ambiguous: tabs });
    });
    it('a learned label that cannot be the session is ignored in favour of the title', () => {
      const learned = new Map([['Token usage optimizatio…', 'e']]);                          // the accident from the log
      const tabs = [tab('1', 'Token usage optimizatio…'), tab('2', 'Email submission on call…')];
      const r = tabsToClose('e', tabs, learned, known);
      expect(r.close).toEqual([]);                                                          // e's own tab is ambiguous with f
      expect(r.ambiguous).toEqual([tabs[1]]);
      expect(tabsToClose('g', tabs, learned, known).close).toEqual([tabs[0]]);              // g gets its tab back
    });
  });
});

describe('candidateSessions (a tab label, in either direction)', () => {
  const known = [
    { sessionId: 'e', title: 'Email submission on calls page' },
    { sessionId: 'f', title: 'Email submission on call sheets' },
    { sessionId: 'g', title: 'Token usage optimization for the indexer' },
  ];
  it('is the trusted learned session alone, else every known session the label fits', () => {
    expect(candidateSessions('Email submission on call…', new Map([['Email submission on call…', 'f']]), known)).toEqual(['f']);
    expect(candidateSessions('Email submission on call…', new Map(), known)).toEqual(['e', 'f']);
    expect(candidateSessions('Token usage optimizatio…', new Map([['Token usage optimizatio…', 'e']]), known)).toEqual(['g']);   // accident ignored
    expect(candidateSessions('Claude Code', new Map(), known)).toEqual([]);
  });
});

describe('pinnedSessions (which sessions the open Claude Code tabs keep ACTIVE)', () => {
  const known = [
    { sessionId: 'e', title: 'Email submission on calls page', lastTs: 500 },
    { sessionId: 'f', title: 'Email submission on call sheets', lastTs: 900 },
    { sessionId: 'g', title: 'Token usage optimization for the indexer', lastTs: 100 },
  ];
  const tab = (key: string, label: string) => ({ key, label });
  it('pins the learned or unique session; for an ambiguous label, the most recently written candidate', () => {
    const tabs = [tab('1', 'Token usage optimizatio…'), tab('2', 'Email submission on call…'), tab('3', 'Claude Code')];
    expect(pinnedSessions(tabs, new Map(), known)).toEqual(['g', 'f']);
    expect(pinnedSessions(tabs, new Map([['Email submission on call…', 'e']]), known)).toEqual(['g', 'e']);
    expect(pinnedSessions([], new Map(), known)).toEqual([]);
  });
  it('knownTitles carries each session\'s last write for that choice', () => {
    const s = buildSnapshot(index, new Map([live('new-not-indexed', { kind: 'running' }, 4)]));
    const k = knownTitles(index, s, firstPrompts(index));
    expect(k.find(t => t.sessionId === 'a')).toEqual({ sessionId: 'a', title: 'Ledger GUI', lastTs: 900 });
    expect(k.find(t => t.sessionId === 'new-not-indexed')).toEqual({ sessionId: 'new-not-indexed', title: 'new-not-', lastTs: 4 });
  });
});
