describe('buildSnapshot', () => {
  it('orders ACTIVE by your last act, newest first — not by state, not by Claude\'s last write (D14)', () => {
    const liveness = new Map<string, Liveness>([
      live('x1', { kind: 'running' }, 990, 50),
      live('x2', { kind: 'attention', reason: 'stalled' }, 10, 99),
      live('x3', { kind: 'attention', reason: 'your-turn' }, 980, 10),
      live('x4', { kind: 'attention', reason: 'question' }, 999, 1),
      live('x5', { kind: 'attention', reason: 'your-turn' }, 970, 20),
    ]);
    expect(buildSnapshot(null, liveness).active.map(r => r.sessionId)).toEqual(['x2', 'x1', 'x5', 'x3', 'x4']);
  });

  it('regression: a session you just started is on top, not under the finished ones — and only you move a row', () => {
    const order = (l: Array<[string, Liveness]>) => buildSnapshot(null, new Map(l)).active.map(r => r.sessionId);
    const vm = (w: number, act: number, st: Liveness['state'] = { kind: 'attention', reason: 'your-turn' }) => live('vm', st, w, act);
    const slack = (w: number, act: number, st: Liveness['state'] = { kind: 'running' }) => live('slack', st, w, act);
    const disk = live('disk', { kind: 'attention', reason: 'your-turn' }, 20, 10);            // tab open since yesterday
    expect(order([vm(200, 100), slack(300, 300), disk])).toEqual(['slack', 'vm', 'disk']);
    // Claude finishes in slack and asks a question in vm: nothing moves
    expect(order([vm(500, 100, { kind: 'attention', reason: 'question' }), slack(400, 300, { kind: 'attention', reason: 'your-turn' }), disk])).toEqual(['slack', 'vm', 'disk']);
    // you answer in vm: it goes on top
    expect(order([vm(600, 600, { kind: 'running' }), slack(400, 300, { kind: 'attention', reason: 'your-turn' }), disk])).toEqual(['vm', 'slack', 'disk']);
  });

  it('the newer of the tail\'s act and the index\'s wins; a session you never acted on sorts by when it began', () => {
    const order = (l: Array<[string, Liveness]>, idx: SearchIndex | null = index) => buildSnapshot(idx, new Map(l)).active.map(r => r.sessionId);
    expect(order([live('a', { kind: 'running' }, 1), live('b', { kind: 'running' }, 1)])).toEqual(['a', 'b']);            // index: a 850, b 600
    expect(order([live('a', { kind: 'running' }, 1), live('b', { kind: 'running' }, 1, 870)])).toEqual(['b', 'a']);       // b's tail knows of a newer act
    expect(order([live('a', { kind: 'running' }, 1, 10), live('b', { kind: 'running' }, 1)])).toEqual(['a', 'b']);        // a's tail is too short: the index's 850 stands
    const scripted: SearchIndex = { ...index, sessions: [meta({ sessionId: 's', lastActTs: 0, firstTs: 700, lastTs: 999 }), meta({ sessionId: 'b', lastActTs: 600 })] };
    expect(order([live('s', { kind: 'running' }, 999), live('b', { kind: 'running' }, 1)], scripted)).toEqual(['s', 'b']);
    expect(order([live('s', { kind: 'running' }, 999), live('b', { kind: 'running' }, 1, 701)], scripted)).toEqual(['b', 's']);
  });

  it('marks the rows that ring (the bell: the ball is in your court and you have not seen it)', () => {
    const liveness = new Map<string, Liveness>([
      live('a', { kind: 'attention', reason: 'your-turn' }, 50), live('b', { kind: 'attention', reason: 'your-turn' }, 40), live('c', { kind: 'running' }, 30),
    ]);
    const s = buildSnapshot(index, liveness, { rings: l => l.sessionId === 'a' });
    expect(s.active.find(r => r.sessionId === 'a')).toMatchObject({ ringing: true });
    expect(s.active.find(r => r.sessionId === 'b')).not.toHaveProperty('ringing');
    expect(buildSnapshot(index, liveness).active.some(r => r.ringing)).toBe(false);          // no rule given: nothing rings
  });

  it('joins index metadata onto live rows', () => {
    const s = buildSnapshot(index, new Map([live('a', { kind: 'running' }, 5)]));
    expect(s.active[0]).toMatchObject({
      sessionId: 'a', title: 'Ledger GUI', project: 'workspaces-aida', branch: 'shobhit/ledger', pr: 20231,
      cwdExists: true, state: 'running', lastWriteMs: 5,
    });
    expect(s.active[0]!.reason).toBeUndefined();
    const t = buildSnapshot(index, new Map([live('d', { kind: 'attention', reason: 'stalled' }, 5)]));
    expect(t.active[0]).toMatchObject({ reason: 'stalled', cwdExists: false });
  });

  it('falls back to the first user prompt, then to the id prefix, for a title', () => {
    const s = buildSnapshot(index, new Map([live('c', { kind: 'running' }, 5), live('zzzz-not-indexed-1234', { kind: 'running' }, 4)]));
    expect(s.active[0]!.title).toBe('Match the Figma frame for the sequences dialog');
    expect(s.active[1]!.title).toBe('zzzz-not');
    expect(s.active[1]!.project).toBe('');
  });

  it('HISTORY excludes ACTIVE ids, sorts by your last act (not Claude\'s last write) and caps at the limit', () => {
    const s = buildSnapshot(index, new Map([live('a', { kind: 'running' }, 5)]), { historyLimit: 2 });
    expect(s.history.map(r => r.sessionId)).toEqual(['c', 'b']);                   // acts: c 650, b 600 — writes: b 800, c 700
    expect(s.history[1]).toMatchObject({ title: 'Deal forecast', lastTs: 800, touchedTs: 600, msgCount: 0, cwdExists: true });
    expect(s.totalSessions).toBe(4);
  });
  it('a closed session you never acted on sorts by when it began', () => {
    const idx: SearchIndex = { ...index, prose: [], sessions: [meta({ sessionId: 'p', lastActTs: 0, firstTs: 300, lastTs: 999 }), meta({ sessionId: 'q', lastActTs: 400, lastTs: 400 })] };
    expect(buildSnapshot(idx, new Map()).history.map(r => [r.sessionId, r.touchedTs])).toEqual([['q', 400], ['p', 300]]);
  });

  it('works before the index exists and carries the indexing flag', () => {
    const s = buildSnapshot(null, new Map([live('a', { kind: 'running' }, 5)]), { indexing: true });
    expect(s.active[0]!.title).toBe('a');
    expect(s.history).toEqual([]);
    expect(s.totalSessions).toBe(0);
    expect(s.indexing).toBe(true);
  });
});

